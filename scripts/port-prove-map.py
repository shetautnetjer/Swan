#!/usr/bin/env python3
"""Proves stage 4's judge for `swan map` can fail, for the part of the map
that is carried (AGENTS.md rule 4: a check never seen failing may be testing
nothing).

Builds copies of the Rust program, each broken in one place on purpose, and
runs scripts/port-map.sh against each, after the unbroken program passes
it. Every copy must be caught.

    scripts/port-prove-map.py            every break
    scripts/port-prove-map.py 3 9        only these (as numbered in a run)
    scripts/port-prove-map.py --fit      whether each break still fits the source; builds nothing

The tree is not touched: the copies are made and built in a temporary
folder. The judge keeps what the Goose program said of each case, so only
the first run of it maps anything with the Goose program.

The copies are built one after another and judged a few at once
(PORT_PROVE_JUDGES, default an eighth of the cores; each judge runs
PORT_MAP_JOBS cases at once). To use more of a machine, start several
runs with ranges of break numbers and PORT_PROVE_JUDGES=1 each.

Exit 0: every break was caught. 1: one was not (the judge has a hole), or a
break no longer fits the source (mend BREAKS below, then run again). 2: the
judge does not pass the unbroken program, so no break proves anything.

Not among the breaks, because the carried part of a map cannot show them:
- what each job is to run (its label, arguments and what it is given to
  run with) and the record written of the indexes (index-manifest.tsv): the
  jobs are first run, and the record first written, in parts still to be
  carried. What says an index is kept is shown, by the line that says so;
- that a chunk with a changed file's users in it gets the time mixed into
  its fingerprint rather than any other value no record holds;
- which of the root's two lists is planned when there are other projects
  (its files less the blank lines, or the list as it is): once other
  projects have taken theirs the list has no blank lines;
- the configs added to the list when a root has no files of its own and
  there are no other projects, and when the list is empty: no chunk is
  planned then, and the list is read only for a chunk or a layer;
- which of the root's files are left to it once other projects have taken
  theirs: the list is first read where the chunks are planned;
- a list of a config's files with a bad one in it taken all the same: the
  reading stops at the bad file, so the end of the list is never seen, and
  a list with no end is not taken either way;
- what TypeScript's part works out for the parts still to come: the
  fingerprint of its files, the words scip-typescript is started with, how
  many chunks are planned beyond "none, one, or more", and a kept list read
  where no chunk will be planned;
- how many indexers run at once when $SWAN_JOBS does not say (half the
  cores, eight at most, less when memory is short): every count from two up
  asks tsc the same way;
- that more projects than one need the patched indexer: without it tsc is
  not asked at all;
- what the stamps keep for the parts still to come: the lines for
  content-stamps.tsv (written at the end of a map), the times, and which
  TypeScript files force a run; and a file stamped by its bytes taken for
  one stamped by its code (no record of indexed text names such a file);
- the two checks that a lost text forces a file to be indexed again say
  the same for rows Swan has not moved, so only the second can be shown;
- what trust adds to the seal (the network, folders to write in): the
  survey is never run trusted, and git's answer is the same with it;
- the room for 255 bytes of other languages' names, and for 65,000 bytes
  of ignored folders;
- the map's lock held by another writer;
- an empty name in an earlier layer's list counted as a file: the check
  that no name is counted twice finds an empty name in every list (a list
  ends in a line end, and what follows it is an empty line), so the
  program without the check for an empty name behaves the same. It was
  break 306 of 371, and the one the judge let through on 2026-11-22.
"""
